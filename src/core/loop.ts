export class Ticker {
  private handle = 0;
  private last = 0;
  private elapsed = 0;
  private running = false;

  constructor(private readonly callback: (dt: number, elapsed: number) => void) {}

  start(): void {
    if (this.running) return;
    this.running = true;
    this.last = performance.now();
    const frame = (now: number) => {
      if (!this.running) return;
      const dt = Math.min(0.05, Math.max(0, (now - this.last) / 1000));
      this.last = now;
      this.elapsed += dt;
      this.callback(dt, this.elapsed);
      this.handle = requestAnimationFrame(frame);
    };
    this.handle = requestAnimationFrame(frame);
  }

  stop(): void {
    this.running = false;
    cancelAnimationFrame(this.handle);
  }
}
